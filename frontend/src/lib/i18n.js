export const DICTS = { es, en }

export function translator(lang) {
  const dict = DICTS[lang] || es
  return (key, vars) => {
    let s = dict[key] ?? es[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v)
    return s
  }
}

export const I18nContext = createContext({ lang: 'es', t: translator('es'), setLang: () => {} })
export const useI18n = () => useContext(I18nContext)

export function formatDate(iso, lang) {
  if (!iso) return ''
  const d = new Date(`${String(iso).slice(0, 10)}T12:00:00`)
  return new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'long', year: 'numeric' }).format(d)
}
